function infoFindSection(id) {
  return INFO_CENTER.sections.find(section => section.id === id) || null;
}

// Route formats: "terms" (section) or "guide/<topicId>" (section + topic, for future contextual "?" help).
// Unknown ids resolve to null so callers can fall back to the menu instead of showing a blank page.
function infoResolveRoute(route) {
  if (!route) return null;
  const [sectionId, topicId = ""] = String(route).split("/");
  const section = infoFindSection(sectionId);
  if (!section) return null;
  const topic = topicId && Array.isArray(section.topics) ? (section.topics.find(item => item.id === topicId) || null) : null;
  return { sectionId: section.id, topicId: topic ? topic.id : "" };
}

function infoLatestVersion() {
  return INFO_CENTER.announcements.latest.version;
}

